"use strict";
const test=require('node:test'),assert=require('node:assert/strict');
const {createPublicationService,blockers}=require('../services/catalogue-publication');
const {createDuplicateService,digest}=require('../services/catalogue-duplicates');
const id='11111111-1111-4111-8111-111111111111',other='22222222-2222-4222-8222-222222222222',auditId='33333333-3333-4333-8333-333333333333';
const subject={id,sku:'APPROVED',product_kind:'fixture',revision:6,is_active:true,published:true,review_status:'approved',approved_revision:6,approved_by:other,selling_price:'100',duplicate_of_product_id:null};
const audit={id:auditId,product_id:id,product_revision:6,status:'completed',corpus_digest:'recorded-before-new-product'};
const review={decision:'approve_distinct',reviewer_id:other};
const facts={primaryCategory:true,primaryImage:true,activeSpecType:true,audit,review,digest:'new-catalogue-digest'};
test('adding another same-kind product does not invalidate completed approval',()=>assert.deepEqual(blockers(subject,facts),[]));
test('editing unrelated product does not invalidate completed approval',()=>assert.deepEqual(blockers(subject,{...facts,digest:'another-revision'}),[]));
test('own revision change still invalidates approval',()=>assert.ok(blockers({...subject,revision:7},facts).length));
test('wrong reviewer still invalidates approval',()=>assert.ok(blockers(subject,{...facts,review:{...review,reviewer_id:id}}).length));
test('latest non-approved review still blocks publication',()=>assert.ok(blockers(subject,{...facts,review:{...review,decision:'reject'}}).length));
test('fresh incomplete subject audit still blocks publication',()=>assert.ok(blockers(subject,{...facts,audit:{...audit,status:'running'}}).length));
test('catalogue growth does not cause a global publication scan or unrelated product mutation',async()=>{
 const calls=[];const client={query:async(sql,args)=>{calls.push([sql,args]);
  if(sql.includes('SELECT * FROM products WHERE id='))return {rows:[{...subject}]};
  if(sql.includes('FROM product_categories'))return {rows:[{id:other}]};
  if(sql.includes('SELECT id FROM product_media'))return {rows:[{id:other}]};
  if(sql.includes('SELECT t.id FROM fixture_specs'))return {rows:[{id:other}]};
  if(sql.includes('SELECT * FROM product_duplicate_audits'))return {rows:[audit]};
  if(sql.includes('SELECT * FROM product_duplicate_reviews'))return {rows:[review]};
  if(sql.startsWith('UPDATE products SET published='))return {rows:[{...subject,published:true}]};
  if(sql.includes('SELECT id,revision,is_active FROM products'))throw Error('global corpus scan must not occur');
  return {rows:[]};}};
 const service=createPublicationService({actor:async()=>{},transaction:fn=>fn(client)});
 const result=await service.set({id:other},id,6,true);assert.equal(result.product.published,true);
 const updates=calls.filter(([sql])=>/^UPDATE products/.test(sql));assert.equal(updates.length,1);assert.equal(updates[0][1][0],id);
});
test('pending review still rejects a changed corpus before recording approval',async()=>{
 const before=[{...subject}],after=[...before,{id:other,revision:1,is_active:true,product_kind:'fixture',specs:{},image_hashes:[]}];
 const pendingAudit={...audit,corpus_digest:digest(before)};const calls=[];
 const client={query:async(sql,args)=>{calls.push(sql);
  if(sql.includes('FROM product_duplicate_audits WHERE id='))return {rows:[pendingAudit]};
  if(sql.includes('SELECT * FROM products WHERE id='))return {rows:[subject]};
  if(sql.includes('SELECT id FROM product_duplicate_audits WHERE product_id='))return {rows:[{id:auditId}]};
  if(sql.includes('SELECT id FROM product_duplicate_reviews'))return {rows:[]};
  if(sql.includes('FROM products p LEFT JOIN fixture_specs'))return {rows:after};
  return {rows:[]};}};
 const service=createDuplicateService({actor:async()=>{},transaction:fn=>fn(client)});
 await assert.rejects(service.review({id:other},auditId,'approve_distinct','Checked'),e=>e.status===409&&/Catalogue evidence changed/.test(e.message));
 assert.ok(!calls.some(sql=>sql.startsWith('INSERT INTO product_duplicate_reviews')||sql.startsWith('UPDATE products')));
});
